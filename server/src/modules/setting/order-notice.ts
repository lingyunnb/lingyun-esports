/**
 * 下单须知（负责人 2026-10-05 商品详情页 v2 方案 B）
 *
 * ## 为什么要做「商品级覆盖 + 平台默认」两层
 *
 * 须知是**逐商品可能不同**的（体验单的保底口径、趣味单的人数限制都不一样），
 * 但绝大多数商品**根本不需要单独写**。如果只有商品级字段，上线当天每个商品都是空窗
 * —— 详情页要么整块不显示（等于没做），要么客户端硬编码一份"临时文案"（下一版必然与
 * 运营口径漂移）。所以按设计稿的**方案甲**做两层：
 *
 *   生效须知 = `product.order_notice`（商品级，管理端「覆盖」）→ 否则 `system_setting.order_notice_default`
 *
 * ## 硬规则（改这里之前先读）
 *
 * - **客户端一个字的须知文案都不许硬编码**：详情页只渲染服务端下发的生效须知
 *   （`GET /public/products/:id` 的 `effectiveOrderNotice`），运营改完下一次请求即生效。
 * - 默认值必须**写进数据库**（迁移 1799000000000），不是代码常量兜底：
 *   管理端要能改这份默认文案，代码常量管理端看不见也改不了。
 *   下面的 `ORDER_NOTICE_DEFAULT_TEXT` 只是**迁移写入的初始值** + 读不到配置行时的最后兜底。
 * - 迁移里的初始值 = 本文件 `ORDER_NOTICE_DEFAULT_TEXT` 逐字一致，避免"库里一份、代码一份"。
 */

