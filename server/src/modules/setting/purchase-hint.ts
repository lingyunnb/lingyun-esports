/**
 * 购买提示（负责人 2026-10-05）：老板端**选择服务页**常驻的一行小字
 *
 * 需求原文：
 * > 「在选择服务那里加一行小字：下单均使用余额非人民币 1 元到账 1 元余额，
 * >   如需下单请联系小云进行余额充值」
 *
 * ## 为什么是「后台可改」而不是客户端常量
 *
 * 这行字的两个可变部分都是**运营口径**，不是产品逻辑：
 * - **联系人**（小云）会换人 —— 值班表一变，App 里写死的名字就成了错误信息，
 *   改一次要发一次版（还要走老板端发布脚本 + 全量用户升级提示）；
 * - **比例**（1 元到账 1 元余额）会随充值活动调整 —— 与 `platform_commission_rate`
 *   同一条铁律（CLAUDE.md 结构规则 8：比例类口径一律后台可配，客户端禁写死）。
 *
 * 因此与 `order_notice_default`、`platform_commission_rate` 完全同一套做法：
 * 落 `system_setting` 一行，管理端改完**下一次请求**即生效，App 不需要发版。
 *
 * ## 硬规则（改这里之前先读）
 *
 * - **客户端一个字的文案都不许硬编码**：选择服务页只渲染 `GET /public/purchase-hint`
 *   下发的 `text`；拿不到 / 空 → **整行不渲染**（不是渲染兜底文案，也不是渲染空行留白）。
 * - 默认值必须**写进数据库**（迁移 1800000000000），不是代码常量兜底：
 *   管理端要能看见并改这份文案。下面的 `PURCHASE_POINTS_HINT_DEFAULT`
 *   只是**迁移写入的初始值** + 管理端读不到配置行时的最后兜底，两者逐字一致。
 * - 负责人原文有错别字（「人名币」）→ 落库默认值用正确的「人民币」。
 */

/** 购买提示的配置 key（`system_setting.setting_key`） */
export const PURCHASE_POINTS_HINT_KEY = 'purchase_points_hint';

/**
 * 购买提示默认文案（= 负责人原文，仅订正错别字「人名币」→「人民币」）。
 *
 * 标点口径：负责人原话是两个空格分隔的短句，这里按中文书面习惯断成
 * 「…非人民币，1 元到账 1 元余额；如需下单…」——逗号分句、分号分层，
 * 客户端 11.5px 小字下 2 行内可完整显示（宽 360dp 机型实测 2 行，见
 * `apps/boss-app/test/product_purchase_hint_test.dart`）。
 */
export const PURCHASE_POINTS_HINT_DEFAULT =
  '下单均使用余额（元），余额仅可用于平台内消费、不可提现；如需充值请联系客服';

